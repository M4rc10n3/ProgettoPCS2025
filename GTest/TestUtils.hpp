TEST(TestUtils, TestOntoTheUnitSphereMoreGeneral)
{
    /* Let's create a polyhedron with a "CoordVertices" matrix composed by columns filled 
    with the same integer */

    GEOPolyhedron testPolyhedron;

    /* Let's define arbitrarily a number of vertices for the polyhedron */
    testPolyhedron.NumVertices = 10;
    int& NumVertices = testPolyhedron.NumVertices;

    Eigen::MatrixXd& CoordVertices = testPolyhedron.CoordVertices;
    CoordVertices.resize(3, NumVertices);

    for(int vertex = 0; vertex < NumVertices; vertex++){
        for(int coordinate = 0; coordinate < 3; coordinate++){
            CoordVertices(coordinate, vertex) = vertex + 1;
        }
    }

    Eigen::MatrixXd oldCoordVertices = CoordVertices;
    /* Let's normalize each column of the copied matrix using pen and paper: we need to divide each element 
    of the column by the value "element * sqrt(3)" because of how we defined "CoordVertices" */
    for(int vertex = 0; vertex < NumVertices; vertex++){
        for(int coordinate = 0; coordinate < 3; coordinate++){
            oldCoordVertices(coordinate, vertex) /= ((vertex + 1) * sqrt(3));
        }
    }
    
    /* Let's use the function we're testing */
    OntoTheUnitSphere(testPolyhedron);
    Eigen::MatrixXd& newCoordVertices = CoordVertices;

    for(int vertex = 0; vertex < NumVertices; vertex++){
        for(int coordinate = 0; coordinate < 3; coordinate++){
            EXPECT_DOUBLE_EQ(newCoordVertices(coordinate, vertex), oldCoordVertices(coordinate, vertex));
        }
    }
}


