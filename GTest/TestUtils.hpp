TEST(TestUtils, TestDistanceSquaredBetween)
{
    /* Let's intialise and define a mtrix of coordintes decided by us. The distance between 
    each couple of vertices (composed by a vertex and the next one) is known by us, because we calculated
    it with pen and paper */
    Eigen::Matrix<double, 3, 8> m;
    m << 61.0/2.0, 11.0/2.0, 32.0/3.0, 5.0/3.0, 9.0/2.0, 1.0/2.0, 4*sqrt(3)/3.0, 2*sqrt(3)/3.0,
         0, 0, 11.0/2.0, 35.0/2.0, 1.0/3.0, 10.0/3.0, 7*sqrt(3)/6.0, 11*sqrt(3)/6.0,
         0, 0, 0, 0, 0, 0, 13*sqrt(3)/9.0, 7*sqrt(3)/9.0;

    /* Let's create a GEOPolyhedron; the matrix defined above will become the "CoordVertices"
    matrix of the structure */
    GEOPolyhedron testPolyhedron;
    testPolyhedron.CoordVertices = m;
    
    /* Let's define two variables which will be used as arguments for the function we're testing:
    "DistanceSquaredBetween" */
    int vertex1 = 0;
    int vertex2 = 1;
    EXPECT_DOUBLE_EQ(625, testPolyhedron.DistanceSquaredBetween(vertex1, vertex2));

    vertex1 = 2;
    vertex2 = 3;
    EXPECT_DOUBLE_EQ(225, testPolyhedron.DistanceSquaredBetween(vertex1, vertex2));

    vertex1 = 4;
    vertex2 = 5;
    EXPECT_DOUBLE_EQ(25, testPolyhedron.DistanceSquaredBetween(vertex1, vertex2));

    vertex1 = 6;
    vertex2 = 7;
    EXPECT_DOUBLE_EQ(4, testPolyhedron.DistanceSquaredBetween(vertex1, vertex2));
}