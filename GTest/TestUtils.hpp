    MatrixXd matrWeights1(5, 5); 
    matrWeights1 << 0, 10, 1, 0, 0,
                   10, 0, 2, 9, 5,
                   1, 2, 0, 0, 20,
                   0, 9, 0, 0, 3,
                   0, 5, 20, 3, 0; 
    int v1_1 = 3;
    int v2_1 = 2;
    // int numVert1 = 5;
    double lengthPath1 = 0.0;
