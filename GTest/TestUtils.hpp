TEST(TestUtils, TestOntoTheUnitSphereTetrahedron)
{
    /* The test will check whether the coordinates of the points belonging to the unit sphere
    generated by our code are "equal as doubles" to the ones found thanks to the function */

    /* Let's create the polyhedron */
    BuildPolyhedra constructor(3, 3);
    constructor.DataPolyhedra();
    GEOPolyhedron polyhedron = constructor.GetPolyhedron();

    /* Let's copy the coordinates of its vertices that we worte in the code as points 
    belonging to the unit sphere */
    Eigen::MatrixXd oldCoordVertices = polyhedron.CoordVertices;

    /* Let's use the function we're testing to update the coordinates of the vertices: 
    this action will not affect the copy "oldCoordVertices" */
    OntoTheUnitSphere(polyhedron);
    /* Let's rename it for code readability */
    Eigen::MatrixXd& newCoordVertices = polyhedron.CoordVertices;

    
    for(int vertex = 0; vertex < polyhedron.NumVertices; vertex++){
        for(int coordinate = 0; coordinate < 3; coordinate++){
            EXPECT_DOUBLE_EQ(newCoordVertices(coordinate, vertex), oldCoordVertices(coordinate, vertex));
        }
    }
}

